/**
 * База профессий теста «Компас».
 *
 * `codes` — профили, которым направление подходит, в порядке убывания
 * точности: первый элемент считается «прямым попаданием», остальные —
 * близкими. Алгоритм в `src/lib/career.ts` собирает топ-3 по позиции
 * в этом списке, остальное показывает аккордеоном по сферам.
 *
 * `scripts/career-unit-check.ts` следит, чтобы ни один из 16 профилей не
 * остался без нормальной выдачи: минимум 3 прямых попадания и минимум
 * 8 совпадений всего.
 *
 * Про экзамены здесь только то, что правда: `focus` сферы говорит, какие
 * навыки в этих направлениях обычно нужны. Конкретное требование —
 * IELTS, SAT или оба — задаёт страна и университет, а не профессия,
 * поэтому такого обещания в данных нет.
 */

export interface CareerSphere {
  id: CareerSphereId;
  label: string;
  /** Имя иконки из `LineIcon` (src/components/ui/CleanUi.tsx). */
  icon: 'book' | 'chart' | 'chat' | 'compass' | 'spark' | 'target';
  focus: string;
}

export interface CareerProfession {
  id: number;
  title: string;
  sphere: CareerSphereId;
  codes: CareerCode[];
  why: string;
}

