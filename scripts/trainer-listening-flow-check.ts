import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { chromium } from 'playwright';
import AxeBuilder from '@axe-core/playwright';
import { checkpointKey, parseRecord } from '../src/lib/trainers/checkpoints';

async function main() {
const base = process.env.TRAINER_CHECK_BASE ?? 'http://127.0.0.1:3043';
const browser = await chromium.launch({ headless: true, args: ['--mute-audio'] });
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
  const page = await context.newPage();
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const historyResponse = await page.goto(base + '/trainers/history');
  assert.equal(historyResponse?.status(), 200);
  await page.getByRole('heading', { name: 'Здесь пока нет сохранённых занятий', exact: true }).waitFor();
  await page.goto(base + '/trainers/listening-replay');
  await page.getByRole('button', { name: 'Сохранять на этом устройстве', exact: true }).click();
  await page.getByRole('button', { name: 'Начать →', exact: true }).first().click();
  await page.getByRole('button', { name: 'Слушать первую попытку →', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Выбери ожидаемый тип' }).waitFor();
  await page.getByLabel('Какой тип ответа подходит в пропуск?', { exact: true }).selectOption('День недели');
  await page.getByLabel('Какое слово поможет отслеживать нужную информацию?', { exact: true }).selectOption('updated');
  await page.route('**/audio/trainers/workshop.wav', route => route.abort());
  await page.getByRole('button', { name: 'Слушать первую попытку →', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Запись не удалось воспроизвести' }).waitFor();
  await page.unroute('**/audio/trainers/workshop.wav');
  page.on('response',response=>{if(response.url().includes('/audio/trainers/'))console.log('audio',response.status(),response.headers()['content-type']);});
  const audioResponse = page.waitForResponse(response => response.url().endsWith('/audio/trainers/workshop.wav') && [200,206].includes(response.status()));
  await page.getByRole('button', { name: 'Слушать первую попытку →', exact: true }).click();
  await audioResponse;
  const key = checkpointKey('listening-replay', 'guest');
  await page.waitForFunction(key => { const raw=localStorage.getItem(key); return raw && JSON.parse(raw).checkpoint?.data.stopped === true; },key);
  await page.reload();
  await page.getByRole('button', { name: 'Продолжить сохранённую', exact: true }).click();
  await page.getByRole('button', { name: 'Слушать первую попытку →', exact: true }).click();
  await page.getByRole('heading', { name: '2. Запиши услышанный ответ', exact: true }).waitFor({ timeout: 60_000 });
  await page.getByLabel('Твой ответ: одно слово', { exact: true }).fill('Tuesday');
  await page.getByLabel('Насколько ты уверен?', { exact: true }).selectOption('Высокая');
  await page.getByRole('button', { name: 'Зафиксировать ответ →', exact: true }).click();
  await page.getByLabel('Что произошло?', { exact: true }).selectOption('Пока не знаю');
  await page.getByRole('button', { name: 'Перейти к проверке →', exact: true }).click();
  await page.getByLabel('Исправленный ответ: одно слово', { exact: true }).fill('Wednesday');
  await page.getByRole('button', { name: 'Проверить исправление →', exact: true }).click();
  await page.getByRole('button', { name: 'Нужна следующая помощь →', exact: true }).click();
  await page.waitForFunction(key => { const raw = localStorage.getItem(key); if (!raw) return false; const r=JSON.parse(raw); return r.checkpoint?.data.phase === 'repair' && r.checkpoint.data.level === 1; }, key);
  await page.reload();
  await page.getByRole('button', { name: 'Продолжить сохранённую', exact: true }).click();
  await page.getByRole('heading', { name: '4. Восстанови ответ', exact: true }).waitFor();
  assert.equal(await page.getByLabel('Исправленный ответ: одно слово', { exact: true }).inputValue(), 'Wednesday');
  await page.getByLabel('Исправленный ответ: одно слово', { exact: true }).fill('Thursday');
  await page.getByRole('button', { name: 'Проверить исправление →', exact: true }).click();
  await page.getByRole('button', { name: 'Попробовать новую запись →', exact: true }).click();
  await page.getByLabel('Какой тип ответа подходит в пропуск?', { exact: true }).selectOption('День недели');
  await page.getByLabel('Какое слово поможет отслеживать нужную информацию?', { exact: true }).selectOption('revised');
  await page.getByRole('button', { name: 'Не могу слушать: использовать текст', exact: true }).click();
  await page.getByLabel('Твой ответ: одно слово', { exact: true }).fill('Friday');
  await page.getByLabel('Насколько ты уверен?', { exact: true }).selectOption('Средняя');
  await page.getByRole('button', { name: 'Зафиксировать ответ →', exact: true }).click();
  await page.getByLabel('Что произошло?', { exact: true }).selectOption('Не было затруднений');
  await page.getByRole('button', { name: 'Перейти к проверке →', exact: true }).click();
  await page.getByRole('heading', { name: 'Результат двух разных записей', exact: true }).waitFor();
  await page.getByText('Первая попытка сделана в текстовом режиме: это чтение, а не проверка слуха.', { exact: true }).waitFor();
  await page.waitForFunction(key => { const raw = localStorage.getItem(key); return raw && JSON.parse(raw).checkpoint?.data.phase === 'result'; }, key);
  const record = parseRecord(await page.evaluate(key => localStorage.getItem(key), key), 'listening-replay')!;
  const data = record.checkpoint!.data as { first: { answer: string; repaired: string; textMode: boolean; stopped: boolean }; transfer: { textMode: boolean } };
  assert.equal(data.first.answer, 'Tuesday');
  assert.equal(data.first.repaired, 'Thursday');
  assert.equal(data.first.textMode, false);
  assert.equal(data.first.stopped, true, 'interrupted first listen remains disclosed after replay completes');
  assert.equal(data.transfer.textMode, true);
  await page.getByRole('button', { name: 'Добавить занятие в историю', exact: true }).click();
  await page.waitForFunction(key => { const raw = localStorage.getItem(key); return raw && JSON.parse(raw).history.length === 1; }, key);
  await page.goto(base + '/trainers/history');
  await page.getByRole('heading', { name: 'Мои занятия', exact: true }).waitFor();
  await page.getByRole('link', { name: 'Продолжить занятие →', exact: true }).waitFor();
  await page.getByRole('button', { name: 'SAT', exact: true }).click();
  await page.getByRole('heading', { name: 'Здесь пока нет сохранённых занятий', exact: true }).waitFor();
  await page.getByRole('button', { name: 'IELTS', exact: true }).click();
  for (const width of [320,390,768,1440]) { await page.setViewportSize({ width,height:900 }); assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1),false); }
  const axe=await new AxeBuilder({ page }).include('main').analyze();
  assert.deepEqual(axe.violations.map(v=>v.id),[]);
  assert.deepEqual(errors,[]);
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>scrollTo(0,0));
  await page.screenshot({path:'artifacts/trainers-complete-033/listening-history-mobile.png'});
  await fs.writeFile('artifacts/trainers-complete-033/listening-flow-smoke.json', JSON.stringify({base,checkedAt:new Date().toISOString(),release:process.env.TRAINER_RELEASE_SHA ?? 'local candidate',guestOnly:true,checks:['history empty','failed audio retry','actual first audio response and playback completion','wrong first answer preserved','repair-level restore after reload','repair','fresh text-mode transfer disclosed','archive','history filters','four widths','axe','no page errors'],limits:['one Listening scenario','transfer uses text mode','no learner account or RLS assertion','no real speech or microphone quality claim']},null,2));
  console.log('PASS guest Listening full browser flow: failed-audio retry, actual first playback, wrong-first/repair/intermediate restore/fresh text-mode transfer, archive/history filters/four widths/axe. No real learner data or account fixture used.');
} finally { await browser.close(); }
}
main().catch(error => { console.error(error); process.exitCode=1; });
